<?php

namespace App\Http\Controllers\Api;

use App\Http\Controllers\Controller;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Storage;
use Symfony\Component\HttpFoundation\BinaryFileResponse;

class FileController extends Controller
{
    /**
     * Stream a video file with byte-range support
     */
    public function stream(Request $request)
    {
        $path = $request->query('path');

        if (!$path) {
            return response()->json(['error' => 'Path is required'], 400);
        }

        // Sanitize path by removing traversal components and leading slashes
        $cleanPath = ltrim(str_replace(['../', '..\\', 'storage/'], '', $path), '/\\');

        $storagePublicBase = realpath(storage_path('app/public'));
        $publicStorageBase = realpath(public_path('storage'));

        $fullPath = null;
        $candidate1 = realpath(storage_path('app/public/' . $cleanPath));
        if ($candidate1 && $storagePublicBase && str_starts_with($candidate1, $storagePublicBase) && is_file($candidate1)) {
            $fullPath = $candidate1;
        } else {
            $candidate2 = realpath(public_path('storage/' . $cleanPath));
            if ($candidate2 && $publicStorageBase && str_starts_with($candidate2, $publicStorageBase) && is_file($candidate2)) {
                $fullPath = $candidate2;
            }
        }

        if (!$fullPath) {
            // Generic 404 without disclosing internal OS server path
            return response()->json(['error' => 'File not found.'], 404);
        }

        // Security Authorization: Protect paid course lessons against unauthorized streaming/piracy.
        // Access is decided by every lesson that actually uses this file, never by a lesson_id the client
        // names (gap analysis GAP-007): naming a lesson of a course you bought must not unlock another course.
        $lessons = \App\Models\Lesson::with('topic.course')
            ->where(function ($q) use ($cleanPath) {
                $q->where('video_path', $cleanPath)->orWhere('video_path', '/' . $cleanPath);
            })
            ->get();
        $lessonId = $request->query('lesson_id');
        if ($lessonId && !$lessons->contains('id', (int) $lessonId)) {
            return response()->json(['error' => 'File not found.'], 404);
        }

        // Preview lessons are public; a file used by any non-preview lesson needs the right person.
        // A temporary signed URL (GAP-008) generated by the server for an enrolled student authorizes streaming directly.
        $hasValidSignature = $request->hasValidSignature();
        $protected = $lessons->reject(fn ($l) => (bool) $l->is_preview);
        if ($protected->isNotEmpty() && !$hasValidSignature) {
            $user = $request->user('sanctum') ?: auth('sanctum')->user() ?: \Illuminate\Support\Facades\Auth::user();

            if (!$user && $request->filled('token')) {
                $token = \Laravel\Sanctum\PersonalAccessToken::findToken((string) $request->query('token'));
                if ($token) {
                    $user = $token->tokenable;
                }
            }

            if (!$user) {
                return response()->json(['error' => 'Authentication required to stream this course video.'], 401);
            }

            $courseIds = $protected->map(fn ($l) => $l->topic?->course_id)->filter()->unique()->values();
            $isAdmin = method_exists($user, 'isAdmin') && $user->isAdmin();
            $isInstructor = $protected->contains(fn ($l) => $l->topic?->course?->instructor_id !== null
                && (int) $l->topic->course->instructor_id === (int) $user->id);
            $isEnrolled = $courseIds->isNotEmpty() && $user->enrollments()
                ->whereIn('course_id', $courseIds->all())
                ->whereIn('status', ['approved', 'completed'])
                ->exists();

            if (!$isAdmin && !$isInstructor && !$isEnrolled) {
                return response()->json(['error' => 'You are not enrolled in this course.'], 403);
            }
        }

        $response = new BinaryFileResponse($fullPath);

        // This helps with iOS byte-range requests
        return $response;
    }
}
